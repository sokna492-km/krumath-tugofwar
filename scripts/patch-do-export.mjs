/**
 * Post-build patches for Cloudflare Workers under /tugofwar:
 * 1. Re-export TugRoom (Nitro drops named DO exports from the main module)
 * 2. Serve /tugofwar/assets/* from ASSETS (/assets/*) without rewriting SSR paths
 *    (full-path strip caused ERR_TOO_MANY_REDIRECTS: / → /tugofwar/ → / …)
 */
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const serverDir = resolve(".output/server");
const indexPath = resolve(serverDir, "index.mjs");
const entryPath = resolve(serverDir, "worker-entry.mjs");
const wranglerPath = resolve(serverDir, "wrangler.json");

if (!existsSync(indexPath)) {
  console.error("Missing .output/server/index.mjs — run build first");
  process.exit(1);
}

const entry = `/**
 * Generated by scripts/patch-do-export.mjs — do not edit by hand.
 */
import nitroApp from "./index.mjs";
export { TugRoom } from "./_ssr/ssr.mjs";

const BASE = "/tugofwar";

function assetPathFromRequest(pathname) {
  if (pathname.startsWith(BASE + "/assets/")) {
    return pathname.slice(BASE.length);
  }
  if (pathname === BASE + "/favicon.svg" || pathname === BASE + "/robots.txt") {
    return pathname.slice(BASE.length);
  }
  if (pathname.startsWith("/assets/") || pathname === "/favicon.svg" || pathname === "/robots.txt") {
    return pathname;
  }
  return null;
}

export default {
  ...nitroApp,
  fetch(request, env, ctx) {
    const url = new URL(request.url);
    const assetPath = assetPathFromRequest(url.pathname);
    if (assetPath && env.ASSETS) {
      const assetUrl = new URL(request.url);
      assetUrl.pathname = assetPath;
      return env.ASSETS.fetch(new Request(assetUrl.toString(), request));
    }
    // Keep /tugofwar/... for SSR + API so the app base does not redirect-loop.
    return nitroApp.fetch(request, env, ctx);
  },
};
`;

writeFileSync(entryPath, entry, "utf8");
console.log("Wrote worker-entry.mjs (asset base map + TugRoom export)");

if (existsSync(wranglerPath)) {
  const cfg = JSON.parse(readFileSync(wranglerPath, "utf8"));
  cfg.main = "worker-entry.mjs";
  writeFileSync(wranglerPath, JSON.stringify(cfg, null, 2) + "\n", "utf8");
  console.log("Updated wrangler.json main → worker-entry.mjs");
}
